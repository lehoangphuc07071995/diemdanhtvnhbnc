function buildIsoForOffsetDay(daysAgo: number, timeHHMMSS: string): string {
  const todayKey = getVNDateKey(new Date().toISOString());
  const base = new Date(`${todayKey}T00:00:00+07:00`);
  const target = new Date(base.getTime() - daysAgo * 86400000);
  const targetKey = getVNDateKey(target.toISOString());
  return `${targetKey}T${timeHHMMSS}+07:00`;
}

